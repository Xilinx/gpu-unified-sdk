inline uint32_t pixelFormatToV4l2(const PixelFormat pixelFormat) noexcept
{
	switch (pixelFormat) {
	case PixelFormat::YUYV:     return V4L2_PIX_FMT_YUYV;
	case PixelFormat::MJPEG:    return V4L2_PIX_FMT_MJPEG;
	case PixelFormat::RGBA8888: return V4L2_PIX_FMT_RGBA32;
	case PixelFormat::RGB888:   return V4L2_PIX_FMT_RGB24;
	case PixelFormat::BGR888:   return V4L2_PIX_FMT_BGR24;
	default: return 0;
	}
}


inline PixelFormat pixelFormatForV4l2(const uint32_t v4l2Format) noexcept
{
	switch (v4l2Format) {
	case V4L2_PIX_FMT_YUYV:   return PixelFormat::YUYV;
	case V4L2_PIX_FMT_MJPEG:  return PixelFormat::MJPEG;
	case V4L2_PIX_FMT_RGBA32: return PixelFormat::RGBA8888;
	case V4L2_PIX_FMT_RGB24:  return PixelFormat::RGB888;
	case V4L2_PIX_FMT_BGR24:  return PixelFormat::BGR888;
	}
	return PixelFormat::Invalid;
}


inline int bitsPerPixelForFormat(PixelFormat format) noexcept
{
	switch (format) {
	case PixelFormat::RGBA8888: return 32;
	case PixelFormat::RGB888:   return 24;
	case PixelFormat::BGR888:   return 24;
	case PixelFormat::YUYV:     return 16;
	default: [[unlikely]]       return 0;
	}
}


inline PixelFormat pixelFormatFromString(const std::string_view & s)
{
	if (s.size() != 4) return PixelFormat::Invalid;
	return *reinterpret_cast<const PixelFormat*>(s.data());
}
